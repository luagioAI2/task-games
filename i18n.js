export const PRIMARY       = "zh";

const pickRaw = (l                )       => {
  const k = (l ?? "").slice(0, 2).toLowerCase();
  return (k in LANGS ? k : PRIMARY)        ;
};

let cur       = PRIMARY;
export const currentLang = ()       => cur;

export function setLang(k      ) {
  cur = k;
  // 同一系统字体栈下 zh / ja 会给出不同的汉字字形,必须显式声明
  document.documentElement.lang = k === "zh" ? "zh-CN" : k;
}

export const pickLang = pickRaw;

/** 活字典:切语言后 T.xxx 立刻返回新语言,无需重建 DOM 引用 */
export const T = new Proxy({}       , {
  get: (_t, k) => (LANGS[cur]       )[k],
})                                             ;
