let current = 'ja';
const listeners = new Set                        ();
export const getLang = () => current;
export function t(key        , params                                  )         {
  const table = STRINGS[current] || STRINGS.ja;
  let s = table[key] ?? STRINGS.ja[key] ?? key;
  if (params) for (const k in params) s = s.split('{' + k + '}').join(String(params[k]));
  return s;
}
export function setLang(lang        ) {
  if (!LANGS.includes(lang)) lang = 'ja';
  current = lang;
  if (typeof document !== 'undefined') document.documentElement.lang = HTML_LANG[lang];
  listeners.forEach((fn) => fn(lang));
}
export const onLang = (fn                        ) => { listeners.add(fn); };
export function detectLang(locale                )         {
  const l = String(locale || '').toLowerCase();
  if (l.startsWith('zh')) return 'zh';
  if (l.startsWith('ja')) return 'ja';
  if (l.startsWith('en')) return 'en';
  return l ? 'en' : 'ja';   // 不认识的语言 → 英文；彻底拿不到 → 游戏主语言（日语）
}
