let cur       = 'en';
export function getLang()       { return cur; }
export function setLang(l      ) {
  cur = l;
  document.documentElement.lang = l === 'zh' ? 'zh-CN' : l;
}
export function pickLang(locale                           )       {
  const s = (locale || '').toLowerCase();
  if (s.startsWith('zh')) return 'zh';
  if (s.startsWith('ja')) return 'ja';
  if (s.startsWith('en')) return 'en';
  return 'en';
}
;                                                        
export function t(k     , vars                                  )         {
  let s = STR[cur][k]          ;
  if (vars) for (const v in vars) s = s.replace('{' + v + '}', String(vars[v]));
  return s;
}
export function elName(i        ) { return STR[cur].el[i]; }
export function elDesc(i        ) { return STR[cur].elDesc[i]; }
