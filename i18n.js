export const PRIMARY       = "ja";
export const ORDER         = ["ja", "zh", "en"];
export const NATIVE                       = { ja: "日本語", zh: "中文", en: "English" };

export function pickLang(l                )       {
  const k = (l ?? "").slice(0, 2).toLowerCase();
  return (k in LANGS ? k : PRIMARY)        ;
}

export function fontStack(lang      )         {
  if (lang === "ja") return '"Hiragino Kaku Gothic ProN","Hiragino Sans","Yu Gothic","Noto Sans JP",system-ui,sans-serif';
  if (lang === "zh") return '"PingFang SC","Hiragino Sans GB","Microsoft YaHei","Noto Sans SC",system-ui,sans-serif';
  return 'system-ui,-apple-system,"Segoe UI",Roboto,"Helvetica Neue",sans-serif';
}

let T                         = LANGS[PRIMARY];
let current       = PRIMARY;

export function setLang(k      )       {
  current = k;
  T = LANGS[k];
  document.documentElement.lang = k;
}
export function getLang()       {
  return current;
}
export function t(key        , vars                                  )         {
  const s = (T                          )[key] ?? (LANGS[PRIMARY]                          )[key] ?? key;
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined ? m : String(vars[k])));
}
