export const LANGS = { zh, en, ja }         ;
                                      
export const PRIMARY       = "zh";
export const pickLang = (l                )       => {
  const k = (l ?? "").slice(0, 2).toLowerCase();
  return (k in LANGS ? k : PRIMARY)        ;
};

let cur       = pickLang(typeof navigator !== "undefined" ? navigator.language : "zh");
export const getLang = () => cur;
export const setLangCode = (l      ) => { cur = l; };

export function t(key        , p                                  )         {
  let s = LANGS[cur][key] ?? LANGS[PRIMARY][key] ?? key;
  if (p) for (const k in p) s = s.split(`{${k}}`).join(String(p[k]));
  return s;
}
/** name of crop/animal id or item id */
export const nm = (id        ) => LANGS[cur]["n." + id] ?? t("i." + id);
export const itemName = (id        ) => t("i." + id);
export const unitOf = (item        ) => LANGS[cur]["u." + item] ?? LANGS[cur]["u.default"];
export const qty = (item        , n        ) => t("qty", { n, u: unitOf(item), name: itemName(item) });

/** resolve log params: c may be a crop/animal/item id */
export function logText(k        , p                                  ) {
  const q                                  = { ...(p ?? {}) };
  if (typeof q.c === "string") q.c = LANGS[cur]["n." + q.c] ?? LANGS[cur]["i." + q.c] ?? q.c;
  return t(k, q);
}

export function fmtDur(ms        )         {
  const s = Math.max(0, Math.ceil(ms / 1000));
  if (s <= 0) return t("t.soon");
  if (s < 60) return t("t.sec", { n: s });
  const m = Math.floor(s / 60), r = s % 60;
  if (m < 60) return r ? t("t.minsec", { m, s: r }) : t("t.min", { n: m });
  return t("t.hour", { h: Math.floor(m / 60), m: m % 60 });
}
