/**
 * recycle.js —— 回收价（卖掉娃娃能换多少张**兑换券**）。
 *
 * ⚠️ 2026-10-23 起单位是**兑换券**，不是娃娃机币。原来「娃娃 → 币」，
 * 而币能直接开局 ⇒ 抓娃娃本身能续玩（「坐着玩就能刷」那条回路）。
 * 现在币只能用积分买，娃娃直接发券，两者不互通。
 *
 * ## 为什么要有这个文件（而不是继续用原来的「跳蚤市场」）
 *
 * 原版是一个完整的市场模拟：玩家自己挂价 → 假买家每 6 秒逛一次 → 按
 * 「挂价 / 行情价」算成交概率 → 卖掉的钱进「销售额」钱包，而那个钱包
 * **可以直接付游玩费**。三个问题同时存在：
 *
 *   ① **价格是玩家定的** ⇒ 自己挂 1 万卖给自己，任何闸门都拦不住；
 *   ② **卖出能换游玩费** ⇒ 抓娃娃本身能赚钱 = 印钞机（原版没有期望值不变量）；
 *   ③ 200 行假买家 / 点赞 / 行情漂移，对玩家**没有信息量**（他也改不了行情）。
 *
 * 现在只有一张**固定价目表**：价格只由稀有度决定，卖出直接铸币。
 * 玩家能做的决策只剩「现在卖还是留着看」——这正是我们要的那个决策。
 *
 * ## ★ 唯一一条不能破的不变量
 *
 * ```
 *   一局的期望产出 = 抓取率 × 平均回收价   <   一局成本（1 币）
 * ```
 *
 * 宿主的 `domain/clawEconomy.ts` 把这条钉成 `E ≤ 0.8`（留 20% 安全边际），
 * 因为它还要接「1 币 ≡ 1 积分」的兑换口 —— E ≥ 1 就是「坐着玩就能刷积分」。
 *
 * 这里的价目表按**最坏情况**（只玩 3 星机台）算：
 *   平均回收价 ≈ 5 ⇒ 抓取率只要低于 **20%** 就不亏。
 * 实际抓取率远低于 20%（爪力、判定、物理都在往下压），所以留量很足。
 *
 * ⚠️ **改价之前先算这一步**。把 3 星从 5 提到 10，等于把保本抓取率从 20% 压到 10%
 * —— 而抓取率是**测不出来**的（它取决于玩家手法），只能靠留量。
 */

import { PRIZE_META } from './config.js'

/**
 * 按稀有度的回收价（兑换券/个）。
 *
 * 下标就是 `PRIZE_META[*].rarity`。0 号位是占位（没有 rarity 0 的奖品）。
 * 为什么要从 rarity 派生而不是写一张 19 行的表：**加了新奖品就不会漏**
 * ——漏一个的下场是 `undefined` 币，而且不报错。
 */
const BY_RARITY = [0, 1, 2, 5]

/**
 * 特例。`snackbox` 的 rarity 是 1，但它是一整盒（10 个）零食，
 * 按 1 张券回收等于把一盒糖当一颗糖卖。
 *
 * 用 `Map` 而不是对象字面量：`OBJ[key] ?? 兜底` 挡不住 `constructor` /
 * `toString` / `__proto__`（它们从 `Object.prototype` 取得到值，`??` 不触发）。
 */
const OVERRIDE = new Map([['snackbox', 3]])

/** 单件最高回收价。宿主 manifest 的 `economy.capPerPrize` 必须 ≥ 它。 */
export const MAX_RECYCLE = 5

/** 单个奖品的回收价。未知 id 一律 1（宁可少给，也不要 NaN 流进账本）。 */
export function recycleValue(id) {
  const over = OVERRIDE.get(id)
  if (over != null) return over
  const rarity = PRIZE_META[id]?.rarity
  const v = BY_RARITY[rarity]
  return Number.isFinite(v) && v > 0 ? v : 1
}
